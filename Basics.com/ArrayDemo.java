public class ArrayDemo {
    public static void main(String[] args) {
        //Array taking user input
        int age[]=new int[5];
        //storing values based on index
        age[0]=10;
        age[1]=20;
        age[2]=30;
        age[3]=40;
        age[4]=50;
        //accessing values based on index
        System.out.print(age[0]+" ");
        System.out.print(age[1]+" ");
        System.out.print(age[2]+" ");
        System.out.print(age[3]+" ");
        System.out.print(age[4]+" ");
    }
}